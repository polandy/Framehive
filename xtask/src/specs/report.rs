//! `cargo xtask spec-report`: a Markdown overview requirement → specification →
//! criteria → tests, with status (ADR 0010 §4).

use std::collections::BTreeMap;
use std::fmt::Write;

use super::document::{NONE_MARKER, Spec};
use super::markers::Marker;

/// Renders the report; specs and tests appear in ID order, so the output is stable.
pub(crate) fn render(specs: &[Spec], markers: &[Marker]) -> String {
    let mut sorted: Vec<&Spec> = specs.iter().collect();
    sorted.sort_by(|a, b| a.id.cmp(&b.id));
    let tests = tests_by_criterion(markers);
    let mut text = String::from("# Specification report\n\n");
    text.push_str("Generated by `cargo xtask spec-report` (ADR 0010). Do not edit.\n\n");
    push_summary(&mut text, &sorted, &tests);
    push_requirements(&mut text, &sorted);
    text.push_str("## Specifications\n");
    for spec in sorted {
        push_spec(&mut text, spec, &tests);
    }
    text
}

/// Test locations for each criterion, such as `IMPORT-001.3` → `["a.rs:12"]`.
fn tests_by_criterion(markers: &[Marker]) -> BTreeMap<String, Vec<&str>> {
    let mut tests: BTreeMap<String, Vec<&str>> = BTreeMap::new();
    for marker in markers {
        tests
            .entry(marker.criterion())
            .or_default()
            .push(&marker.location);
    }
    tests
}

fn push_summary(text: &mut String, specs: &[&Spec], tests: &BTreeMap<String, Vec<&str>>) {
    let mut by_status: BTreeMap<&str, usize> = BTreeMap::new();
    for spec in specs {
        *by_status.entry(spec.status.as_str()).or_default() += 1;
    }
    let statuses: Vec<String> = by_status
        .iter()
        .map(|(status, count)| format!("{count} {status}"))
        .collect();
    let criteria: Vec<String> = specs.iter().flat_map(|spec| criterion_ids(spec)).collect();
    let tested = criteria.iter().filter(|id| tests.contains_key(*id)).count();
    // Writing to a String cannot fail.
    let _ = writeln!(
        text,
        "{} specifications ({}); {tested} of {} criteria have a test.\n",
        specs.len(),
        statuses.join(", "),
        criteria.len()
    );
}

fn push_requirements(text: &mut String, specs: &[&Spec]) {
    let mut by_requirement: BTreeMap<NaturalKey, (&str, Vec<String>)> = BTreeMap::new();
    for spec in specs {
        for origin in &spec.origin {
            by_requirement
                .entry(natural_key(origin))
                .or_insert_with(|| (origin, Vec::new()))
                .1
                .push(format!("{} ({})", spec.id, spec.status));
        }
    }
    text.push_str("## By requirement\n\n| Requirement | Specifications |\n|---|---|\n");
    for (requirement, linked) in by_requirement.into_values() {
        let _ = writeln!(text, "| {requirement} | {} |", linked.join(", "));
    }
    text.push('\n');
}

/// Text runs and the numbers after them, so `G2` sorts before `G14` and `2.7` before `2.10`.
type NaturalKey = Vec<(String, u64)>;

fn natural_key(text: &str) -> NaturalKey {
    let mut key = Vec::new();
    let mut letters = String::new();
    let mut characters = text.chars().peekable();
    while let Some(character) = characters.next() {
        let Some(digit) = character.to_digit(10) else {
            letters.push(character);
            continue;
        };
        let mut number = u64::from(digit);
        while let Some(next) = characters.peek().and_then(|c| c.to_digit(10)) {
            number = number.saturating_mul(10).saturating_add(u64::from(next));
            characters.next();
        }
        key.push((std::mem::take(&mut letters), number));
    }
    key.push((letters, 0));
    key
}

fn push_spec(text: &mut String, spec: &Spec, tests: &BTreeMap<String, Vec<&str>>) {
    let origin = if spec.origin.is_empty() {
        NONE_MARKER.to_owned()
    } else {
        spec.origin.join(", ")
    };
    let _ = writeln!(
        text,
        "\n### {} – {}\n\nStatus: {} · Origin: {origin} · File: `{}`\n",
        spec.id,
        escape(&spec.title),
        spec.status,
        spec.file
    );
    text.push_str("| Criterion | Tests | Status |\n|---|---|---|\n");
    for id in criterion_ids(spec) {
        let (locations, status) = match tests.get(&id) {
            Some(found) => (found.iter().map(|l| format!("`{l}`")).collect(), "tested"),
            None => (Vec::new(), "no test"),
        };
        let listed = if locations.is_empty() {
            NONE_MARKER.to_owned()
        } else {
            locations.join("<br>")
        };
        let _ = writeln!(text, "| {id} | {listed} | {status} |");
    }
}

fn criterion_ids(spec: &Spec) -> Vec<String> {
    spec.criteria
        .iter()
        .filter(|number| !spec.removed.contains(number))
        .map(|number| format!("{}.{number}", spec.id))
        .collect()
}

/// A `|` would end a table cell.
fn escape(cell: &str) -> String {
    cell.replace('|', "\\|")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec(id: &str, status: &str, origin: &[&str], criteria: &[u32]) -> Spec {
        Spec {
            file: format!("specs/core/{id}-x.md"),
            id: id.to_owned(),
            title: "Title | with bar".to_owned(),
            status: status.to_owned(),
            origin: origin.iter().map(|o| (*o).to_owned()).collect(),
            criteria: criteria.to_vec(),
            ..Spec::default()
        }
    }

    fn marker(spec_id: &str, number: u32, location: &str) -> Marker {
        Marker {
            location: location.to_owned(),
            spec_id: spec_id.to_owned(),
            number,
        }
    }

    #[test]
    fn requirements_sort_by_letter_then_number() {
        let specs = [spec(
            "CORE-001",
            "draft",
            &["G14", "G2", "2.10", "2.7"],
            &[],
        )];
        let report = render(&specs, &[]);
        let positions: Vec<Option<usize>> = ["| 2.7 ", "| 2.10 ", "| G2 ", "| G14 "]
            .into_iter()
            .map(|row| report.find(row))
            .collect();
        assert!(positions.iter().all(Option::is_some), "{report}");
        assert!(positions.is_sorted(), "{report}");
    }

    #[test]
    fn renders_requirements_specs_criteria_and_tests() {
        let specs = [
            spec("CORE-002", "accepted", &[], &[1]),
            spec("CORE-001", "implemented", &["B19", "2.7"], &[1, 2]),
        ];
        let markers = [
            marker("CORE-001", 1, "a.rs:3"),
            marker("CORE-001", 1, "b.rs:9"),
        ];
        let report = render(&specs, &markers);
        let expected = "# Specification report\n\n\
            Generated by `cargo xtask spec-report` (ADR 0010). Do not edit.\n\n\
            2 specifications (1 accepted, 1 implemented); 1 of 3 criteria have a test.\n\n\
            ## By requirement\n\n| Requirement | Specifications |\n|---|---|\n\
            | 2.7 | CORE-001 (implemented) |\n| B19 | CORE-001 (implemented) |\n\n\
            ## Specifications\n\n\
            ### CORE-001 – Title \\| with bar\n\n\
            Status: implemented · Origin: B19, 2.7 · File: `specs/core/CORE-001-x.md`\n\n\
            | Criterion | Tests | Status |\n|---|---|---|\n\
            | CORE-001.1 | `a.rs:3`<br>`b.rs:9` | tested |\n\
            | CORE-001.2 | – | no test |\n\n\
            ### CORE-002 – Title \\| with bar\n\n\
            Status: accepted · Origin: – · File: `specs/core/CORE-002-x.md`\n\n\
            | Criterion | Tests | Status |\n|---|---|---|\n\
            | CORE-002.1 | – | no test |\n";
        assert_eq!(report, expected);
    }

    #[test]
    fn leaves_removed_criteria_out() {
        let mut core = spec("CORE-001", "implemented", &[], &[1, 2]);
        core.removed.push(2);
        let report = render(&[core], &[marker("CORE-001", 1, "a.rs:3")]);
        assert!(report.contains("1 of 1 criteria have a test"), "{report}");
        assert!(!report.contains("CORE-001.2"), "{report}");
    }
}
